# ── C: long_session — six turns; a decision and accumulated facts ────────────

def gen_long_session(dest):
    """docs/decision.md carries the codename; three large fact sheets follow.

    The task is driven as six continuation turns (see the manifest's `prompts`),
    so a harness must accumulate state across process boundaries: the codename
    stated in turn 1 cannot be re-derived in turn 6 without it surviving turns
    2-5, whose reads are ~60KB each.
    """
    channel = "ORBITAL-7"
    facts = {"1": "DELTA-11", "2": "SIGMA-23", "3": "OMEGA-31"}
    os.makedirs(os.path.join(dest, "docs"), exist_ok=True)
    with open(os.path.join(dest, "docs", "decision.md"), "w") as fh:
        fh.write(
            "# Engagement decision\n\n"
            f"The retention codename for this engagement is **{channel}**.\n\n"
            "Record it exactly as written.\n"
        )
    for n, value in facts.items():
        rng = rng_for(f"long_session:facts-{n}")
        body = fill_to(60_000, rng, f"Fact sheet {n}")
        body += f"\n\n---\nFACT{n}={value}\n"
        with open(os.path.join(dest, "docs", f"facts-{n}.md"), "w") as fh:
            fh.write(body)
    return channel, facts


