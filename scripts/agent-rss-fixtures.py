# ── C: pressure_read — four ~350KB documents, one fragment each ──────────────

def gen_pressure_read(dest):
    """4 x ~350KB briefs; the tail of each holds FRAGMENTn=VALUE."""
    parts = [("brief-a.md", "ECHO"), ("brief-b.md", "FOXTROT"),
             ("brief-c.md", "GOLF"), ("brief-d.md", "HOTEL")]
    os.makedirs(os.path.join(dest, "docs"), exist_ok=True)
    values = []
    for i, (name, value) in enumerate(parts, 1):
        rng = rng_for(f"pressure_read:{name}")
        body = fill_to(350_000, rng, f"Brief {name}")
        # Same construction as large_read, scaled up: the fragment is only
        # reachable by a read that reaches the tail of a much larger document.
        body += f"\n\n---\nFRAGMENT{i}={value}\n"
        with open(os.path.join(dest, "docs", name), "w") as fh:
            fh.write(body)
        values.append(value)
    return "-".join(values)


# ── C: aggregate_scan — 250 files, one exact sum ─────────────────────────────

def gen_aggregate_scan(dest):
    """250 record files; keys are quota_*/ledger_*/ttl_*/cursor_*/shard_*.

    Returns the exact sum of every `quota_*` value, which the verifier matches
    as a whole line — so a near miss is a failure, not a rounding argument.
    """
    rng = rng_for("aggregate_scan")
    records = os.path.join(dest, "records")
    os.makedirs(records, exist_ok=True)
    total = 0
    decoy_kinds = ("ledger", "ttl", "cursor", "shard")
    for p in range(250):
        lines = []
        for j in range(rng.randint(18, 34)):
            val = rng.randrange(1, 1000)
            total += val
            lines.append(f"quota_{rng.choice(VOCAB)}_{j}={val}")
            other = f"{rng.choice(decoy_kinds)}_{rng.choice(VOCAB)}_{j}"
            lines.append(f"{other}={rng.randrange(1, 1000)}")
        with open(os.path.join(records, f"part-{p:03d}.txt"), "w") as fh:
            fh.write("\n".join(lines) + "\n")
    return total


# ── C: noisy_tool — a command whose output is ~2MB, token on the last line ───

def gen_noisy_tool(dest):
    """A deterministic log emitter; the answer is only on the final line.

    Forces the harness to take a very large tool result, find the tail fact in
    it, and not lose it while the result dominates the turn.
    """
    token = hashlib.sha256(f"{SEED}:noisy_tool".encode()).hexdigest()[:16]
    tools = os.path.join(dest, "tools")
    os.makedirs(tools, exist_ok=True)
    script = (
        "import random\n"
        "import sys\n"
        "\n"
        f"rng = random.Random({SEED})\n"
        "out = sys.stdout\n"
        "for i in range(24000):\n"
        "    out.write(\n"
        '        "2026-09-16T00:00:%02dZ INFO worker[%d] shard=%d step=%d "\n'
        '        "state=nominal latency_ms=%d queue=%d\\n"\n'
        "        % (i % 60, i % 8, i % 97, i, rng.randrange(1, 500), rng.randrange(0, 64))\n"
        "    )\n"
        f'out.write("TRACE_TOKEN={token}\\n")\n'
    )
    with open(os.path.join(tools, "emit_logs.py"), "w") as fh:
        fh.write(script)
    return token


