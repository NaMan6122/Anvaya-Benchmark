PIPELINE_SPEC_MD = '''# Pipeline specification

Implement the modules under `src/pipeline/` so every test in `test_pipeline.py`
passes. Do not modify the tests.

## clean.normalize(text) -> str

Lowercase `text`, collapse every run of whitespace to a single space, then strip
leading and trailing whitespace. `"  Hello   World "` -> `"hello world"`.

## chunk.split(text, size) -> list[str]

Split normalized `text` on spaces into consecutive chunks of at most `size`
words; the final chunk holds the remainder. `size` is at least 1. Empty input
returns `[]`. `split("a b c d e", 2)` -> `["a b", "c d", "e"]`.

## score.tf(words) -> dict[str, int]

Count occurrences of each word in the list `words`.

## score.top_k(counts, k) -> list[str]

Return the `k` most frequent words from `counts`, ordered by count descending,
then alphabetically for ties. `k` at least 1. If `k` exceeds the number of
distinct words, return all of them.
'''

