#!/usr/bin/env python3
"""Generate the agent-RSS benchmark corpus.

Produces deterministic seed projects under fixtures/
plus manifest.json describing each task, the prompt, and how to verify it.

The corpus is organised by *memory-pressure class* rather than by feature, so a
harness's RSS can be attributed to a cause:

  noop            trivial prompt, no tool calls        -> agent loop + client floor
  wide_read       ~200-file tree, one needle           -> traversal + tool-result churn
  large_read      3 x ~200KB documents                 -> large tool-result buffering
  pressure_read   4 x ~350KB briefs                    -> large-resident-context reads
  deep_read       8 x ~25KB volumes, early decision    -> big resident context
  aggregate_scan  250 files, one exact sum             -> many-read accumulation
  noisy_tool      ~2MB command output, tail token      -> tool-result churn at scale
  edit_tool       fix a bug + create a module + test   -> multi-tool edit pipeline
  build_pkg       3 stubs + spec + tests, implement    -> multi-file build pipeline
  long_session    6 continuation turns (see `prompts`) -> cross-process retention

The first five classes date from corpus v2 and are regenerated byte-identically
(same seed, per-tag RNG streams), so v2 records remain comparable task by task.
The five added classes form corpus v3; `manifest.json` names the schema `agent-
rss-corpus/3` and the corpus hash changes accordingly.

Traversal is scaffolded via SCAFFOLD_LEVELS (default 2). 0 = flat, 2 = nested
per-module packages.

Prompts are deliberately harness-neutral: they describe the work ("read", "write",
"run") and never name a specific harness's tool vocabulary, so every harness gets
the same instruction. Fixtures are deterministic (fixed seed) so a corpus hash
identifies a run.

Usage:
    scripts/agent-rss-fixtures.py            # regenerate in place
    SCAFFOLD_LEVELS=0 scripts/agent-rss-fixtures.py
"""
import hashlib
import json
import os
import random
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "fixtures")
SEED = 20260915

# Layout: 0 = flat (all modules in src/), 2 = nested (packages/pkg_NN/module_MM.py).
SCAFFOLD_LEVELS = int(os.environ.get("SCAFFOLD_LEVELS", "2"))

VOCAB = """lattice quorum ingest shard ledger cursor backoff ttl hydration invariant
manifest reconcile snapshot epoch watermark redaction throttle idempotent predicate
adapter facade reservoir tokenizer checkpoint nominal quiescent delta bounded""".split()


def rng_for(tag):
    return random.Random(f"{SEED}:{tag}")


def sentence(rng):
    n = rng.randint(8, 22)
    words = [rng.choice(VOCAB) for _ in range(n)]
    return " ".join(words).capitalize() + "."


def paragraph(rng, sentences=7):
    return " ".join(sentence(rng) for _ in range(sentences))


def fill_to(target_bytes, rng, heading):
    """Build a plausible technical document of roughly target_bytes."""
    parts = [f"# {heading}\n"]
    while sum(len(p) for p in parts) < target_bytes:
        parts.append("\n## " + " ".join(rng.choice(VOCAB) for _ in range(3)).title() + "\n")
        for _ in range(rng.randint(3, 6)):
            parts.append("\n" + paragraph(rng) + "\n")
    return "".join(parts)


# ── C: wide_read — many small modules, one needle ────────────────────────────

def gen_wide_read(dest):
    """~200 modules; exactly one defines MAGIC_OFFSET = 4821."""
    rng = rng_for("wide_read")
    n_pkgs, per_pkg = 25, 8
    needle_pkg, needle_mod = 7, 3
    needle_rel = f"src/packages/pkg_{needle_pkg:02d}/module_{needle_mod:02d}.py"

    if SCAFFOLD_LEVELS == 0:
        needle_rel = None

    for p in range(n_pkgs):
        for m in range(per_pkg):
            if SCAFFOLD_LEVELS == 0:
                rel = f"src/module_{p * per_pkg + m:03d}.py"
            else:
                rel = f"src/packages/pkg_{p:02d}/module_{m:02d}.py"
            is_needle = (rel == needle_rel)

            body = [
                '"""Module generated for the corpus."""',
                "",
            ]
            if rng.random() < 0.20 or is_needle:
                # Decoys carry the same constant name with a different value.
                val = 4821 if is_needle else rng.randrange(1000, 9999)
                body += [f"MAGIC_OFFSET = {val}", ""]

            for f in range(rng.randint(3, 6)):
                body += [
                    f"def handle_{rng.choice(VOCAB)}_{f}(payload, ctx):",
                    f'    """{sentence(rng)}"""',
                    f"    return allocate(payload, ctx, window={rng.randint(2, 4096)})",
                    "",
                ]
            body += ["def allocate(payload, ctx, window=8):", "    return payload", ""]

            path = os.path.join(dest, rel)
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w") as fh:
                fh.write("\n".join(body))

    return needle_rel


# ── C: large_read — three big documents, one part of a code each ─────────────

def gen_large_read(dest):
    """3 x ~200KB docs; the last line of each holds PARTn=VALUE."""
    parts = [("spec-a.md", "ALPHA"), ("spec-b.md", "BRAVO"), ("spec-c.md", "CHARLIE")]
    os.makedirs(os.path.join(dest, "docs"), exist_ok=True)
    for i, (name, value) in enumerate(parts, 1):
        rng = rng_for(f"large_read:{name}")
        body = fill_to(200_000, rng, f"Specification {name}")
        # The part token sits at the very end, so it is only reachable by a read
        # that actually reaches the tail of the document.
        body += f"\n\n---\nPART{i}={value}\n"
        with open(os.path.join(dest, "docs", name), "w") as fh:
            fh.write(body)
    return "-".join(v for _, v in parts)


# ── C: deep_read — eight volumes, decision stated in the first ───────────────

def gen_deep_read(dest):
    """8 x ~25KB volumes; volume 1 states the decision."""
    channel = "ORBITAL-7"
    os.makedirs(os.path.join(dest, "docs"), exist_ok=True)
    for v in range(1, 9):
        rng = rng_for(f"deep_read:{v}")
        body = fill_to(25_000, rng, f"Engagement Volume {v}")
        if v == 1:
            body += (
                "\n\n---\n\n## Decision\n\n"
                f"The release channel for this engagement is **{channel}**.\n"
            )
        else:
            body += f"\n\n---\n\nEnd of volume {v}.\n"
        with open(os.path.join(dest, "docs", f"volume-{v}.md"), "w") as fh:
            fh.write(body)
    return channel


